@testable import KernovaKit

@Suite("ClipboardPasteboardReader", .caseScoped)
@MainActor
struct ClipboardPasteboardReaderTests {
    // MARK: - Fixtures

    private let scratch = TestScratchDirectory(prefix: "reader-tests")

    init() throws {
        try FileManager.default.createDirectory(at: scratch.url, withIntermediateDirectories: true)
    }

    private static let promisedFileURLType = NSPasteboard.PasteboardType(
        "com.apple.pasteboard.promised-file-url")
    private static let promisedFileNameType = NSPasteboard.PasteboardType(
        "com.apple.pasteboard.promised-file-content-type")

    /// The offer `pasteboard` makes, or `nil` with the outcome recorded as an
    /// issue when it makes none.
    private func offer(
        _ pasteboard: FakeReadPasteboard
    ) async -> (source: ClipboardOfferSource, lost: Int)? {
        let outcome = await ClipboardPasteboardReader.readOffer(from: pasteboard, publisher: .elsewhere(), sizeOf: nil)
        guard case .offer(let source, let lost) = outcome else {
            Issue.record("expected an offer, got \(outcome)")
            return nil
        }
        return (source, lost)
    }

    // MARK: - Markers

    @Test(
        "a transient or auto-generated marker suppresses the whole offer, naming which",
        arguments: [
            ClipboardSnapshotPolicy.transientMarkerUTI,
            ClipboardSnapshotPolicy.autoGeneratedMarkerUTI,
        ])
    func markerSuppressesOffer(marker: String) async {
        let pasteboard = FakeReadPasteboard()
        // A real password/expansion item carries the marker alongside content;
        // the whole offer goes, not just the marker rep.
        pasteboard.setItem([
            (type: NSPasteboard.PasteboardType(marker), data: Data([1])),
            (type: .string, data: Data("noise".utf8)),
        ])

        guard
            case .suppressed(let reason) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, publisher: .elsewhere(), sizeOf: nil)
        else {
            Issue.record("Expected .suppressed")
            return
        }
        #expect(
            reason
                == (marker == ClipboardSnapshotPolicy.transientMarkerUTI
                    ? .transientSnapshot : .autoGeneratedSnapshot))
    }

    // MARK: - File classification

    @Test("a promised file URL already written on disk is offered as the file, under its name")
    func promisedFileURLIsOfferedAsTheFile() async throws {
        let file = scratch.url.appendingPathComponent("promised.txt")
        try Data("body".utf8).write(to: file)

        let pasteboard = FakeReadPasteboard()
        pasteboard.setItems([
            FakePasteboardItem([
                (type: Self.promisedFileURLType, data: Data(file.absoluteString.utf8))
            ])
        ])

        let offered = try #require(await offer(pasteboard))
        #expect(offered.lost == 0)
        let representation = try #require(offered.source.items.first?.representations.first)
        #expect(offered.source.items.count == 1)
        #expect(representation.storage == .file)
        #expect(String(decoding: representation.name, as: UTF8.self) == "promised.txt")
    }

    @Test("a copied file deleted since is a loss, never its URL as content")
    func vanishedFileIsALossNotItsURL() async {
        let gone = URL(fileURLWithPath: "/nonexistent/\(UUID().uuidString)/notes.txt")
        let pasteboard = FakeReadPasteboard()
        pasteboard.setItem([
            (type: .fileURL, data: Data(gone.absoluteString.utf8)),
            (type: .URL, data: Data(gone.absoluteString.utf8)),
        ])

        guard
            case .nothingOfferable(let lost) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, publisher: .elsewhere(), sizeOf: nil)
        else {
            Issue.record("Expected .nothingOfferable")
            return
        }
        #expect(lost == 1)
    }

    @Test("a missed URL is not a loss while a promise is still outstanding")
    func outstandingPromiseIsNotALoss() async {
        let gone = URL(fileURLWithPath: "/nonexistent/\(UUID().uuidString)/pending.txt")
        let pasteboard = FakeReadPasteboard()
        // The promise advertises a file still to be written, so its URL missing
        // today says nothing; `NSFilePromiseReceiver` can still deliver it.
        pasteboard.setItems([
            FakePasteboardItem(
                types: [.fileURL, Self.promisedFileNameType],
                bytes: [.fileURL: Data(gone.absoluteString.utf8)])
        ])

        guard
            case .nothingOfferable(let lost) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, publisher: .elsewhere(), sizeOf: nil)
        else {
            Issue.record("Expected .nothingOfferable")
            return
        }
        #expect(lost == 0)
    }

    // MARK: - Empty

    @Test("a pasteboard holding no item at all is empty, not a loss")
    func emptyPasteboard() async {
        let pasteboard = FakeReadPasteboard()

        guard
            case .empty = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, publisher: .elsewhere(), sizeOf: nil)
        else {
            Issue.record("Expected .empty")
            return
        }
    }

    // MARK: - A promised write of this process

    /// A far side's offer: answers each INLINE pull with `bytes` and each file pull with `url`, counting both.
    private final class CountingPuller: ClipboardItemPulling {
        let bytes: Data
        let url: URL
        private let counts = Locked<(bytes: Int, files: Int)>((0, 0))
        init(bytes: Data, url: URL) {
            self.bytes = bytes
            self.url = url
        }
        var pulls: (bytes: Int, files: Int) { counts.withLock { $0 } }
        func pullBytes(item: Int, representation: Int, completion: @escaping @Sendable (Data?) -> Void) {
            counts.withLock { $0.bytes += 1 }
            completion(bytes)
        }
        func pullFile(item: Int, representation: Int, completion: @escaping @Sendable (URL?) -> Void) {
            counts.withLock { $0.files += 1 }
            completion(url)
        }
        func whenEnded(_ handler: @escaping @Sendable () -> Void) {}
    }

    /// Two VMs' publishers over the Mac's one pasteboard, the first holding its write of a far-side offer of one
    /// item of `representation`, served through `puller`.
    private func twoPublishers(
        writing representation: Representation, through puller: CountingPuller, registry: LazyClipboardProviderRegistry
    ) -> (pasteboard: FakePasteboard, writer: ClipboardPasteboardPublisher, other: ClipboardPasteboardPublisher) {
        let pasteboard = FakePasteboard()
        let ledger = ClipboardWriteLedger()
        let writer = ClipboardPasteboardPublisher(pasteboard: pasteboard, providerRegistry: registry, ledger: ledger)
        let other = ClipboardPasteboardPublisher(pasteboard: pasteboard, providerRegistry: registry, ledger: ledger)
        var item = OfferedItem()
        item.representations = [representation]
        let outcome = writer.publish(
            [item], concealed: false, pasteCeiling: .max, puller: puller,
            serving: .init(token: Data(repeating: 1, count: 16), connection: ClipboardConnectionID()))
        #expect(outcome == .written)
        return (pasteboard, writer, other)
    }

    @Test("another publisher's promised file is offered through its puller, none of its promises read")
    func anotherPublishersFileIsPulledUpstream() async throws {
        let file = scratch.url.appendingPathComponent("a.bin")
        try Data("upstream file".utf8).write(to: file)
        let registry = LazyClipboardProviderRegistry()
        defer { registry.releaseAllForTesting() }
        let puller = CountingPuller(bytes: Data(), url: file)
        let (pasteboard, _, other) = twoPublishers(
            writing: .make(TypeDescriptor(appleUTI: "public.data"), .file, size: 13, name: "a.bin"),
            through: puller, registry: registry)

        let outcome = await ClipboardPasteboardReader.readOffer(from: pasteboard, publisher: other, sizeOf: nil)
        #expect(pasteboard.promiseReads.isEmpty)
        guard case .offer(let source, let lost) = outcome else {
            Issue.record("expected an offer, got \(outcome)")
            return
        }
        #expect(lost == 0)
        #expect(source.items.map { $0.representations.map(\.storage) } == [[.file]])
        #expect(source.items.first?.representations.first?.promised == true)
        #expect(try await source.serve(item: 0, representation: 0) == .file(file))
        #expect(puller.pulls.files == 1)
        #expect(pasteboard.promiseReads.isEmpty)
    }

    @Test("another publisher's promised text is offered through its puller, none of its promises read")
    func anotherPublishersTextIsPulledUpstream() async throws {
        let registry = LazyClipboardProviderRegistry()
        defer { registry.releaseAllForTesting() }
        let puller = CountingPuller(bytes: Data("upstream text".utf8), url: scratch.url)
        let (pasteboard, _, other) = twoPublishers(
            writing: .make(TypeDescriptor(appleUTI: NSPasteboard.PasteboardType.string.rawValue), .inline, size: 0),
            through: puller, registry: registry)

        let outcome = await ClipboardPasteboardReader.readOffer(from: pasteboard, publisher: other, sizeOf: nil)
        guard case .offer(let source, _) = outcome else {
            Issue.record("expected an offer, got \(outcome)")
            return
        }
        #expect(source.items.first?.representations.first?.promised == true)
        #expect(try await source.serve(item: 0, representation: 0) == .bytes(Data("upstream text".utf8)))
        #expect(puller.pulls.bytes == 1)
        #expect(pasteboard.promiseReads.isEmpty)
    }

    @Test("the reader's own publisher's promised write offers nothing, none of its promises read")
    func ownPromisedWriteIsHeldByTheFarSide() async {
        let registry = LazyClipboardProviderRegistry()
        defer { registry.releaseAllForTesting() }
        let puller = CountingPuller(bytes: Data("upstream text".utf8), url: scratch.url)
        let (pasteboard, writer, _) = twoPublishers(
            writing: .make(TypeDescriptor(appleUTI: NSPasteboard.PasteboardType.string.rawValue), .inline, size: 0),
            through: puller, registry: registry)

        let outcome = await ClipboardPasteboardReader.readOffer(from: pasteboard, publisher: writer, sizeOf: nil)
        guard case .heldByFarSide = outcome else {
            Issue.record("expected .heldByFarSide, got \(outcome)")
            return
        }
        #expect(pasteboard.promiseReads.isEmpty)
        #expect(puller.pulls.bytes == 0)
    }

    // MARK: - Sizing files

    @Test("a symlink is sized as what it resolves to")
    func symlinkIsSizedAsItsTarget() throws {
        let target = scratch.url.appendingPathComponent("target.txt")
        try Data("target body".utf8).write(to: target)
        let link = scratch.url.appendingPathComponent("link.txt")
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: target)

        #expect(ClipboardPasteboardReader.byteCount(ofItemAt: link) == Data("target body".utf8).count)
    }

    @Test("a file this process cannot open is not sized")
    func unreadableFileHasNoSize() throws {
        let readable = scratch.url.appendingPathComponent("readable.txt")
        try Data("body".utf8).write(to: readable)
        let sealed = scratch.url.appendingPathComponent("sealed.txt")
        try Data("secret".utf8).write(to: sealed)
        try FileManager.default.setAttributes([.posixPermissions: 0], ofItemAtPath: sealed.path)
        defer {
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o644], ofItemAtPath: sealed.path)
        }

        #expect(ClipboardPasteboardReader.byteCount(ofItemAt: readable) == Data("body".utf8).count)
        #expect(ClipboardPasteboardReader.byteCount(ofItemAt: sealed) == nil)
    }

    @Test("a folder is sized by the injected walk")
    func folderIsSizedByTheWalk() throws {
        let folder = scratch.url.appendingPathComponent("Tree", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)

        #expect(ClipboardPasteboardReader.byteCount(ofItemAt: folder, sizeOf: { _ in 4_096 }) == 4_096)
    }

    @Test("with no walk, a folder is sized 0 whatever it holds")
    func anUnwalkedFolderHasNoSize() throws {
        let folder = scratch.url.appendingPathComponent("Unwalked", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try Data("inside".utf8).write(to: folder.appendingPathComponent("inside.txt"))

        #expect(ClipboardPasteboardReader.byteCount(ofItemAt: folder, sizeOf: nil) == 0)
    }

    // MARK: - The readability check

    @Test(
        "the check offers what opens and what is not on this Mac yet, and leaves out what the system refuses or is gone",
        arguments: [
            (Int32(0), true), (EDEADLK, true), (EPERM, false), (EACCES, false), (ENOENT, false),
        ])
    func readabilityFollowsTheOpen(errno: Int32, offered: Bool) throws {
        let file = scratch.url.appendingPathComponent("checked.txt")
        try Data("checked".utf8).write(to: file)
        let source = ClipboardPasteboardReader.readableSource(for: file, opening: { _ in errno })
        #expect((source == file) == offered)
    }
}
