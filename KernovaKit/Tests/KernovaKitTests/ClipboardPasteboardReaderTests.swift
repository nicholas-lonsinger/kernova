import AppKit
import Foundation
import KernovaTestSupport
import KernovaWire
import Testing
import UniformTypeIdentifiers

@testable import KernovaKit

@Suite("ClipboardPasteboardReader", .caseScoped)
@MainActor
struct ClipboardPasteboardReaderTests {
    // MARK: - Fixtures

    private let scratch = TestScratchDirectory(prefix: "reader-tests")

    init() throws {
        try FileManager.default.createDirectory(at: scratch.url, withIntermediateDirectories: true)
    }

    private static let promisedFileURLType = NSPasteboard.PasteboardType(
        "com.apple.pasteboard.promised-file-url")
    private static let promisedFileNameType = NSPasteboard.PasteboardType(
        "com.apple.pasteboard.promised-file-content-type")

    /// The offer `pasteboard` makes, or `nil` with the outcome recorded as an
    /// issue when it makes none.
    private func offer(
        _ pasteboard: FakeReadPasteboard
    ) async -> (source: ClipboardOfferSource, lost: Int)? {
        let outcome = await ClipboardPasteboardReader.readOffer(from: pasteboard, sizeOf: nil)
        guard case .offer(let source, let lost) = outcome else {
            Issue.record("expected an offer, got \(outcome)")
            return nil
        }
        return (source, lost)
    }

    // MARK: - Markers

    @Test(
        "a transient or auto-generated marker suppresses the whole offer, naming which",
        arguments: [
            ClipboardSnapshotPolicy.transientMarkerUTI,
            ClipboardSnapshotPolicy.autoGeneratedMarkerUTI,
        ])
    func markerSuppressesOffer(marker: String) async {
        let pasteboard = FakeReadPasteboard()
        // A real password/expansion item carries the marker alongside content;
        // the whole offer goes, not just the marker rep.
        pasteboard.setItem([
            (type: NSPasteboard.PasteboardType(marker), data: Data([1])),
            (type: .string, data: Data("noise".utf8)),
        ])

        guard
            case .suppressed(let reason) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, sizeOf: nil)
        else {
            Issue.record("Expected .suppressed")
            return
        }
        #expect(
            reason
                == (marker == ClipboardSnapshotPolicy.transientMarkerUTI
                    ? .transientSnapshot : .autoGeneratedSnapshot))
    }

    // MARK: - File classification

    @Test("a promised file URL already written on disk is offered as the file, under its name")
    func promisedFileURLIsOfferedAsTheFile() async throws {
        let file = scratch.url.appendingPathComponent("promised.txt")
        try Data("body".utf8).write(to: file)

        let pasteboard = FakeReadPasteboard()
        pasteboard.setItems([
            FakePasteboardItem([
                (type: Self.promisedFileURLType, data: Data(file.absoluteString.utf8))
            ])
        ])

        let offered = try #require(await offer(pasteboard))
        #expect(offered.lost == 0)
        let representation = try #require(offered.source.items.first?.representations.first)
        #expect(offered.source.items.count == 1)
        #expect(representation.storage == .file)
        #expect(String(decoding: representation.name, as: UTF8.self) == "promised.txt")
    }

    @Test("a copied file deleted since is a loss, never its URL as content")
    func vanishedFileIsALossNotItsURL() async {
        let gone = URL(fileURLWithPath: "/nonexistent/\(UUID().uuidString)/notes.txt")
        let pasteboard = FakeReadPasteboard()
        pasteboard.setItem([
            (type: .fileURL, data: Data(gone.absoluteString.utf8)),
            (type: .URL, data: Data(gone.absoluteString.utf8)),
        ])

        guard
            case .nothingOfferable(let lost) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, sizeOf: nil)
        else {
            Issue.record("Expected .nothingOfferable")
            return
        }
        #expect(lost == 1)
    }

    @Test("a missed URL is not a loss while a promise is still outstanding")
    func outstandingPromiseIsNotALoss() async {
        let gone = URL(fileURLWithPath: "/nonexistent/\(UUID().uuidString)/pending.txt")
        let pasteboard = FakeReadPasteboard()
        // The promise advertises a file still to be written, so its URL missing
        // today says nothing; `NSFilePromiseReceiver` can still deliver it.
        pasteboard.setItems([
            FakePasteboardItem(
                types: [.fileURL, Self.promisedFileNameType],
                bytes: [.fileURL: Data(gone.absoluteString.utf8)])
        ])

        guard
            case .nothingOfferable(let lost) = await ClipboardPasteboardReader.readOffer(
                from: pasteboard, sizeOf: nil)
        else {
            Issue.record("Expected .nothingOfferable")
            return
        }
        #expect(lost == 0)
    }

    // MARK: - Empty

    @Test("a pasteboard holding no item at all is empty, not a loss")
    func emptyPasteboard() async {
        let pasteboard = FakeReadPasteboard()

        guard
            case .empty = await ClipboardPasteboardReader.readOffer(from: pasteboard, sizeOf: nil)
        else {
            Issue.record("Expected .empty")
            return
        }
    }

    // MARK: - Resolving files

    @Test("a symlink crosses as its target's bytes under the name that was copied")
    func symlinkResolvesToTargetUnderTheCopiedName() throws {
        let target = scratch.url.appendingPathComponent("target.txt")
        try Data("target body".utf8).write(to: target)
        let link = scratch.url.appendingPathComponent("link.txt")
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: target)

        let intake = ClipboardPasteboardReader.resolve(filesAt: [link])

        #expect(intake.skipped == 0)
        let rep = try #require(intake.representations.first)
        #expect(rep.filename == "link.txt")
        #expect(rep.byteCount == Data("target body".utf8).count)
    }

    @Test("a file this process cannot open is skipped, not offered as an empty one")
    func unreadableFileIsSkipped() throws {
        let readable = scratch.url.appendingPathComponent("readable.txt")
        try Data("body".utf8).write(to: readable)
        let sealed = scratch.url.appendingPathComponent("sealed.txt")
        try Data("secret".utf8).write(to: sealed)
        try FileManager.default.setAttributes([.posixPermissions: 0], ofItemAtPath: sealed.path)
        defer {
            try? FileManager.default.setAttributes(
                [.posixPermissions: 0o644], ofItemAtPath: sealed.path)
        }

        let intake = ClipboardPasteboardReader.resolve(filesAt: [readable, sealed])

        #expect(intake.representations.map(\.filename) == ["readable.txt"])
        #expect(intake.skipped == 1)
    }

    @Test("a folder becomes a directory source rep sized by the injected walk")
    func folderBecomesADirectorySourceRep() throws {
        let folder = scratch.url.appendingPathComponent("Tree", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)

        let intake = ClipboardPasteboardReader.resolve(filesAt: [folder], sizeOf: { _ in 4_096 })

        let rep = try #require(intake.representations.first)
        #expect(rep.isDirectory)
        #expect(rep.filename == "Tree")
        #expect(rep.byteCount == 4_096)
    }

    @Test("with no walk, a folder becomes a directory source rep of no size")
    func anUnwalkedFolderHasNoSize() throws {
        let folder = scratch.url.appendingPathComponent("Unwalked", isDirectory: true)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try Data("inside".utf8).write(to: folder.appendingPathComponent("inside.txt"))

        let intake = ClipboardPasteboardReader.resolve(filesAt: [folder], sizeOf: nil)

        let rep = try #require(intake.representations.first)
        #expect(rep.isDirectory)
        #expect(rep.directorySourceURL == folder)
        #expect(rep.byteCount == 0)
    }

    // MARK: - The readability check

    @Test(
        "the check offers what opens and what is not on this Mac yet, and leaves out what the system refuses or is gone",
        arguments: [
            (Int32(0), true), (EDEADLK, true), (EPERM, false), (EACCES, false), (ENOENT, false),
        ])
    func readabilityFollowsTheOpen(errno: Int32, offered: Bool) throws {
        let file = scratch.url.appendingPathComponent("checked.txt")
        try Data("checked".utf8).write(to: file)
        let source = ClipboardPasteboardReader.readableSource(for: file, opening: { _ in errno })
        #expect((source == file) == offered)
    }
}
