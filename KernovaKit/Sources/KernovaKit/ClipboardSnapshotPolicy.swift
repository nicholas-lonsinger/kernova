import Foundation

/// The single policy deciding which pasteboard representations may cross the
/// clipboard channel.
///
/// Shared by every intake site — the guest agent's pasteboard poll and the host
/// window's Paste/drag gestures — so both ends apply identical filtering. There
/// is **no size cap**: a representation past `maxResidentInlineBytes` streams
/// to a staging file and is served back memory-mapped, so what the rules cover
/// is identity skips — representation types that must never be sent or applied
/// — plus the empty-payload skip.
public enum ClipboardSnapshotPolicy {
    /// Why a representation was excluded from a snapshot.
    public enum SkipReason: Equatable, Sendable {
        /// An `org.nspasteboard.*` marker representation dropped from a synced
        /// payload: the markers are metadata flags, not content, so their bytes
        /// never cross while the content alongside them still does — unless the
        /// whole snapshot is suppressed (`transientSnapshot` /
        /// `autoGeneratedSnapshot`).
        case transientMarkerType

        /// File URLs, file promises, and legacy filename lists name host-side
        /// filesystem locations that are meaningless — or misleading — inside the
        /// guest, and promises need a sender-side callback flow that cannot cross
        /// the wire. A `dyn.` type whose encoding names nothing could be any of
        /// them.
        case fileReferenceType

        /// Zero-byte representations carry no information.
        case emptyData

        /// The whole snapshot was dropped because it carried an
        /// `org.nspasteboard.TransientType` marker — content the source app will
        /// restore or replace within seconds (a clipboard manager re-injecting a
        /// past entry, a TextExpander/Keyboard Maestro expansion), never a
        /// deliberate copy.
        case transientSnapshot

        /// The whole snapshot was dropped because it carried an
        /// `org.nspasteboard.AutoGeneratedType` marker — content an app placed
        /// with no copy intent (e.g. a Grammarly correction) that clipboard
        /// managers ignore by convention.
        case autoGeneratedSnapshot
    }

    /// One excluded representation and the rule that excluded it.
    public struct Skipped: Equatable, Sendable {
        /// The excluded representation's UTI.
        public let uti: String

        /// The rule that excluded it.
        public let reason: SkipReason

        /// Creates a skip record.
        public init(uti: String, reason: SkipReason) {
            self.uti = uti
            self.reason = reason
        }
    }

    /// Result of evaluating a raw pasteboard snapshot.
    ///
    /// Never silently empty: when the input was non-empty but `content`
    /// is, `skipped` records why every representation was excluded.
    public struct Outcome: Sendable {
        /// The representations that survived every rule.
        public let content: ClipboardContent

        /// The representations excluded, with reasons.
        public let skipped: [Skipped]
    }

    // MARK: - Marker types

    /// `org.nspasteboard.TransientType` — the source app will restore or replace
    /// the pasteboard within seconds; the content is never a deliberate copy.
    public static let transientMarkerUTI = "org.nspasteboard.TransientType"

    /// `org.nspasteboard.AutoGeneratedType` — content placed with no copy intent
    /// (e.g. a Grammarly correction); not something the user expects to paste.
    public static let autoGeneratedMarkerUTI = "org.nspasteboard.AutoGeneratedType"

    /// `org.nspasteboard.ConcealedType` — confidential content (password
    /// managers), synced so it can still be pasted but hidden from the host
    /// clipboard window's display.
    public static let concealedMarkerUTI = "org.nspasteboard.ConcealedType"

    /// What to do with an entire pasteboard snapshot, decided from its
    /// `org.nspasteboard.*` marker types before any data is read.
    public enum SnapshotDisposition: Equatable, Sendable {
        /// Sync the snapshot normally (still subject to per-representation
        /// filtering via `evaluate`).
        case allow

        /// Sync the snapshot but mark its `ClipboardContent` concealed, so the
        /// host clipboard window hides it behind a placeholder while the bytes
        /// still cross to be pasted into the peer.
        case conceal

        /// Drop the entire snapshot so nothing crosses; the reason distinguishes
        /// the transient and auto-generated markers for user-facing messaging.
        case suppress(SkipReason)
    }

    /// Classifies a pasteboard snapshot from the full UTI list of its first item.
    ///
    /// Must see the *unfiltered* type list (markers included), so call it before
    /// `shouldSkipBeforeReading` strips the `org.nspasteboard.*` reps.
    public static func disposition(forTypes utis: [String]) -> SnapshotDisposition {
        let markers = Markers(types: utis)
        if markers.transient { return .suppress(.transientSnapshot) }
        if markers.autoGenerated { return .suppress(.autoGeneratedSnapshot) }
        if markers.concealed { return .conceal }
        return .allow
    }

    /// The [nspasteboard.org](http://nspasteboard.org) markers among a
    /// pasteboard's types.
    public struct Markers: Equatable, Sendable {
        /// `org.nspasteboard.ConcealedType`: the content is confidential.
        public var concealed = false
        /// `org.nspasteboard.TransientType`: the content will be restored or
        /// replaced within seconds, and stays out of history.
        public var transient = false
        /// `org.nspasteboard.AutoGeneratedType`: an app placed the content with
        /// no copy by the user.
        public var autoGenerated = false

        /// The markers among `types`.
        public init<Types: Sequence<String>>(types: Types) {
            for type in types {
                switch type.lowercased() {
                case ClipboardSnapshotPolicy.concealedMarkerUTI.lowercased(): concealed = true
                case ClipboardSnapshotPolicy.transientMarkerUTI.lowercased(): transient = true
                case ClipboardSnapshotPolicy.autoGeneratedMarkerUTI.lowercased(): autoGenerated = true
                default: break
                }
            }
        }
    }

    /// `true` for types excluded by identity alone (`transientMarkerType` /
    /// `fileReferenceType`).
    ///
    /// Intake sites filter their type lists with this first and read data only
    /// for the survivors, so these skips cost nothing.
    public static func shouldSkipBeforeReading(uti: String) -> Bool {
        skipReasonBeforeReading(uti: uti) != nil
    }

    /// Applies every rule, in order, over (uti, data) pairs read from one pasteboard item.
    ///
    /// Copied *files* take the disk-backed `.file` path and never pass through
    /// here. A dynamic (`dyn.*`) UTI is kept unless the legacy type it encodes
    /// is excluded: the encoding is a deterministic function of that type, so
    /// macOS↔macOS round-trips reproduce the exact type.
    public static func evaluate(_ raw: [(uti: String, data: Data)]) -> Outcome {
        var kept: [ClipboardContent.Representation] = []
        var skipped: [Skipped] = []

        for (uti, data) in raw {
            if let reason = skipReasonBeforeReading(uti: uti) {
                skipped.append(Skipped(uti: uti, reason: reason))
                continue
            }
            if data.isEmpty {
                skipped.append(Skipped(uti: uti, reason: .emptyData))
                continue
            }
            kept.append(ClipboardContent.Representation(uti: uti, data: data))
        }

        return Outcome(content: ClipboardContent(representations: kept), skipped: skipped)
    }

    /// Why `uti` is excluded by identity alone, judged by every name AppKit
    /// reads it as (``PasteboardTypeIdentity``), so no spelling of an excluded
    /// type passes.
    private static func skipReasonBeforeReading(uti: String) -> SkipReason? {
        let identity = PasteboardTypeIdentity(uti)
        if identity.isMarker { return .transientMarkerType }
        if identity.isFileReference { return .fileReferenceType }
        return nil
    }

    /// `true` for a type that names a file on this machine or promises one.
    static func isFileReference(uti: String) -> Bool {
        skipReasonBeforeReading(uti: uti) == .fileReferenceType
    }

    /// Whether `data` may be served under `uti` on a pasteboard.
    ///
    /// A type AppKit reads a URL from admits only URLs with a scheme other than
    /// `file`, so no URL flavor hands a reader a file on this machine: every
    /// string its bytes carry — each string of a property list, as the Apple
    /// URL type's `[url, base]` is, or else the bytes as UTF-8 — must parse as
    /// such a URL. Any other type admits any bytes.
    public static func admits(_ data: Data, servedAs uti: String) -> Bool {
        guard PasteboardTypeIdentity(uti).carriesURL else { return true }
        let strings: [String]
        if let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) {
            strings = Self.strings(in: plist)
        } else {
            strings = [String(decoding: data, as: UTF8.self)]
        }
        let padding = CharacterSet.whitespacesAndNewlines.union(.controlCharacters)
        return strings.allSatisfy { string in
            let trimmed = string.trimmingCharacters(in: padding)
            guard !trimmed.isEmpty else { return true }
            guard let scheme = URL(string: trimmed)?.scheme else { return false }
            return scheme.lowercased() != "file"
        }
    }

    private static func strings(in plist: Any) -> [String] {
        switch plist {
        case let string as String: [string]
        case let array as [Any]: array.flatMap(strings(in:))
        case let dictionary as [String: Any]: dictionary.keys.map { $0 } + dictionary.values.flatMap(strings(in:))
        default: []
        }
    }
}
